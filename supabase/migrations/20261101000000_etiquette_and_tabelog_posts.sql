- **Zaru or mori soba:** cold on a tray. Order this first at a good shop.
- **Kake soba:** hot in broth. A good choice in winter, with noodles that soften as you eat, so don't wait around.
- **Ten zaru:** cold soba with tempura on the side.
- **Soba-mae:** drinks and small plates before the noodles. Tamagoyaki and sake are the classics, and it's how regulars spend an evening.

