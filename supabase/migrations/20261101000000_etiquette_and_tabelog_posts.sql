## How to read Tabelog scores on a real listing

**Check the review count next to the score.** Tabelog scores on thin history can jump around. Kikuya, a Kanazawa sushi counter, scores 3.77 on 39 reviews. Atsuta Houraiken's main shop in Nagoya scores 3.71 on 4,406 reviews. Because reviews are weighted, neither number is wrong, but the second has far more history behind it.

**Look for the Tabelog 100 badge.** Called *Hyakumeiten* (hundred famous shops) in Japanese, these lists run by genre and often by region, like Ramen WEST or Soba EAST. They appear in the awards row of a listing.

**Treat the Tabelog Award as a separate signal.** Nominees need a score of 4.00 or higher for at least a month in the qualifying period, and then [Tabelog users vote on the winners](https://award.tabelog.com/en/2024/guide) for Gold, Silver and Bronze. Awards can outlast a number too: [Tamawarai](https://tabelog.com/en/tokyo/A1306/A130601/13129390/), a Tokyo soba shop, lists a 2026 Bronze and scores 3.90 today.

**Don't compare it with Google.** The scales don't line up. One reviewer of a Hiroshima okonomiyaki shop noted 3.69 on Tabelog next to 4.2 on Google for the same place, and that 3.69 is the stronger signal, since only about 3% of restaurants reach 3.5.

**Check the practical details last.** A 3.9 that's closed on your only free day or won't take your card isn't useful. Filter by hours and payment on [the TabeDog map](/) once you've settled on a score to aim for.

