## How to eat okonomiyaki with a hera

The *hera* is the small metal spatula, and it's both knife and fork. [Savor Japan's guide](https://savorjapan.com/contents/discover-oishii-japan/how-to-eat-okonomiyaki-in-japan) describes eating directly from it as normal in Kansai, and many locals see it as the proper way.

**Cut straight down.** Press the edge through the pancake from above. Sawing back and forth pulls it apart.

**Slide and lift.** Work the hera under a bite-size piece and raise it. Keep the piece small, because a heavy one falls off.

**Blow first.** The hera comes straight off the griddle and so does the food. Don't touch the metal to your lips right away.

**Use a plate if you'd prefer.** Moving a slice to a small plate and using chopsticks is accepted everywhere. Ask for a plate and nobody will think twice.

**Keep it on the heat, but not forever.** The griddle keeps the meal hot and crisps the base, and it also keeps cooking. If the base gets dark, ask the staff to turn the heat down or eat a little faster.

## How to eat okonomiyaki in Osaka

Osaka's version is thick and soft, so it's cut like a pizza or in a grid. At shops where you grill your own, follow the staff's lead, and wait for the base to set before flipping. Most cooks also advise against flattening it with the spatula, which squeezes out the air that keeps it fluffy.

Sauce, mayonnaise and bonito flakes go on after cooking, so add only as much as you like. Many shops also serve *negiyaki*, a green-onion version that's often finished with soy instead of sweet sauce.

## How to eat okonomiyaki in Hiroshima

Hiroshima's version is a tall stack held together by egg and noodles. [GetHiroshima](https://gethiroshima.com/features/food-and-drink/hiroshimas-soul-food-okonomiyaki/) calls it the city's soul food. Sit at the counter if you can, because the chef slides it right to your spot on the griddle.

Cut small squares that go all the way through the stack, so each bite has noodles, cabbage and egg. Locals simply call it okonomiyaki, so there's no need for the name "Hiroshima-yaki." The crisp fried noodles at the bottom are the reason to eat it on the griddle instead of on a plate.

