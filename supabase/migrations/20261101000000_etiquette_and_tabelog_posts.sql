## How to eat sushi, step by step

**Use hands or chopsticks.** Both are fine at nearly every counter. Guides disagree on which is more traditional, so pick whichever keeps the piece intact. Many restaurants hand you a damp towel for your fingers.

**Dip the fish, lightly.** Sushi rice soaks up soy sauce and falls apart, so turn the piece over and touch the topping to the sauce. [This guide to sushi basics](https://www.gltjp.com/en/article/item/10053/) covers the same approach. If a piece won't flip, dab the rice briefly. Pour only a little soy into your dish, since you can always add more.

**Check before you dip.** At omakase counters the chef often brushes on soy or adds salt. If the piece looks glazed, or the chef says it's ready as is, eat it plain.

**Eat it soon, in one bite.** The chef shapes each piece for that moment, with the rice still at its best temperature. Some guides allow two bites for a big piece. Putting a half-eaten piece back on the plate is the thing to avoid.

**Leave the wasabi alone.** Good chefs put the right amount inside the piece. Mixing it into your soy is common at casual places and frowned on by purists. At a counter, skip it, and ask politely if you'd like more or none at all.

**Eat ginger between pieces.** *Gari* (pickled ginger) is there to reset your palate. It doesn't go on top of the fish.

## How to eat sushi at a counter

The food rules are easy. Counter manners are where a little preparation pays off.

**Arrive on time.** Many high-end counters start every guest together, so a late arrival holds up the whole room. One reviewer of Sushi-ya Kozakura below describes this kind of synchronized start.

**Skip the perfume.** Scent competes with the fish. Sushi Nanba Hibiya below asks guests in its reservation notes to avoid strong perfumes and colognes.

**Ask before you photograph.** Some counters set limits, and Sushi Nanba's notes cover filming too. A quick question to the chef takes care of it.

**Tell them about allergies when you book.** Omakase is hard to change halfway through.

