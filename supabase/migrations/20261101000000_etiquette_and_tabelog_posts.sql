## How to eat soba, step by step

These steps are for cold *zaru* or *mori* soba, the plain style that shows off the noodle best.

**Try a few strands plain.** [One Japanese dining guide](https://gurunavi.com/en/japanfoodie/2017/07/how-to-eat-japanese-soba-noodles-a-step-by-step-guide.html) suggests a first bite with no sauce, so you can taste the buckwheat. It's a small step, and at a shop that mills its own flour it's the point of the meal.

**Add condiments to taste.** Stir some of the sliced green onion and wasabi into the dipping sauce, or skip them. Wasabi is optional, and there's no wrong amount.

**Lift a small bite.** Take only a few strands, enough to eat in one go. A big clump drags too much sauce and gets messy.

**Dip the ends.** The common advice is to dip about a third of the noodles, since the sauce is strong. Consider it a guideline: dip more if you like it salty.

**Raise the cup.** Hold the sauce cup up near your mouth. [The Japan Foundation's lesson on zaru soba](https://www.erin.jpf.go.jp/en/lesson/08/let-us-try) walks through the same basic motions. It keeps sauce off the table and your shirt.

**Slurp.** It's the expected way to eat soba. The air carries the buckwheat aroma, which is why many soba fans say slurping tastes better too. Eating quietly is OK if you can't get the hang of it.

**Don't let it sit.** Cold soba sticks together as it dries, so start soon after it arrives.

## How to eat soba with sobayu

Near the end of the meal, the staff may bring a small pot of cloudy hot water. That's *sobayu*, the water the noodles cooked in.

Pour some into your leftover dipping sauce, taste, and add more until the strength suits you. Then drink it like soup. It's the local way to finish, and leaving it untouched isn't rude, but you'd miss the best part of the tray.

