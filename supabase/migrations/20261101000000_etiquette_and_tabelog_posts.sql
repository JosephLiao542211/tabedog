At a counter, no: the chef has already added wasabi where it belongs. At a kaiten (conveyor belt) shop, it's your call, and sources disagree about how much it matters.

### Do I have to eat sushi in one bite?

It's the usual advice, since a piece is built to be eaten whole. Two bites won't cause a scene if a piece is large, but don't put a half-eaten piece back down.

### Can I ask for no wasabi?

Yes. Say *sabi nuki* (without wasabi) to the chef, ideally at the start of the meal.

