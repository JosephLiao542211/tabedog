## How to eat hitsumabushi in four portions

Your tray arrives with a wooden tub, a small empty bowl, a paddle, condiments and a pot of *dashi* (broth) or tea. [Hitsumabushi guides](https://tabimaniajapan.com/culture/food-culture/hitsumabushi-guide-how-to-eat-nagoyas-famous-grilled-eel) describe the same order. Score the rice into quarters with the paddle before you start, so you don't eat too much in round one.

**First: plain.** Scoop a quarter into your small bowl and eat it as it is. This is the only time you taste the grilled eel and sauce alone, so notice the crisp skin.

**Second: with condiments.** Add some of the *yakumi* (condiments) to the next quarter. Expect some mix of green onion, wasabi and nori. Mix lightly and eat.

**Third: with broth.** Add condiments again if you like, then pour hot dashi or tea over the third quarter, like *ochazuke* (rice in broth). It's a lighter finish after the rich sauce.

**Fourth: your favorite.** Repeat whichever round you liked best. That's your only decision of the meal.

## How to eat hitsumabushi without the common mistakes

**Use the bowl.** The tub is the serving dish. Keep eating from the small bowl, and don't pour broth into the tub.

**Ask for help.** It's perfectly fine to ask the staff how to eat it, and [many shops have illustrated pamphlets](https://tabimaniajapan.com/culture/food-culture/hitsumabushi-guide-how-to-eat-nagoyas-famous-grilled-eel) with English versions. Asking counts as good manners here.

**Don't save the eel.** Part of learning how to eat hitsumabushi is pacing: take some eel and rice together in each scoop so the last quarter isn't plain rice.

**Don't skip a round to be polite.** You can leave out the wasabi or the broth if you don't like them. The four steps are a suggestion, and no one is keeping score. [Wikipedia's overview](https://en.wikipedia.org/wiki/Hitsumabushi) has more on where the dish comes from.

