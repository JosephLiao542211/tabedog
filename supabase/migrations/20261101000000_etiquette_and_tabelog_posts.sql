## Frequently asked questions

### Is there only one way how to eat hitsumabushi?

No. The order is a guide meant to show the eel three ways, so skip any step you don't enjoy.

### What is poured over hitsumabushi?

Hot dashi, or tea at some restaurants. It goes over rice and eel in your small bowl for the third round.

### How much does hitsumabushi cost in Nagoya?

At the three restaurants above, Tabelog's budget bands start at ¥4,000–¥4,999 for lunch and reach ¥6,000–¥7,999 for dinner at the Matsuzakaya branch.

### How is hitsumabushi different from una-ju?

Una-ju is eel over rice in a box, eaten one way. Hitsumabushi is chopped and eaten in stages.

