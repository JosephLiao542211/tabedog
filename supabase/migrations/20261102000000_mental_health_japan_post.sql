  $post$Long trips and new jobs abroad are hard on the mind as well as the body. Jet lag, a language you can't read, and being far from the people you'd usually call all add up, even on a trip you've been looking forward to. This guide covers mental health in Japan from a visitor's point of view: who to call, how care works, what it costs, and how to keep your own support going while you're here. Phone numbers and hours are as of November 2026, so check the linked pages before you rely on them.

## If you need help right now

**In an emergency, call 119 for an ambulance or 110 for the police.** Both are free from any phone. If you or someone else is in immediate danger, call before anything else.

**TELL Lifeline (English): 0800-300-8355.** [TELL](https://telljp.com/lifeline/) runs a free, anonymous English-language phone and chat line for anyone in Japan. It isn't open around the clock. Weekends run continuously from Saturday morning to Monday night, and weekdays usually run from 9:00 to 23:00 (later on Fridays). The hours change, so check [the current schedule](https://telljp.com/tell-hours/).

**Yorisoi Hotline (many languages): 0120-279-338, then press 2.** The [Yorisoi Hotline](https://www.since2011.net/yorisoi/en/) is toll free and takes calls every day from 10:00 to 22:00, in English, Chinese, Korean, Tagalog, Spanish, Portuguese, Thai, Vietnamese, Nepali and Indonesian. Which languages are available depends on the time.

**Japan Visitor Hotline: 050-3816-2787.** The tourism board's [24-hour line](https://www.japan.travel/en/plan/hotline/) answers in English, Chinese and Korean. It isn't a counseling service, but it can help in an emergency, such as finding medical care when you're ill or after an accident.

## How mental health care works in Japan

**Psychiatry and therapy are paid for differently.** A visit to a psychiatrist for a diagnosis or prescription is covered by Japan's national health insurance, so residents pay the usual 30% share. Talk therapy with a private psychologist or counselor usually isn't covered, and sessions [typically cost ¥10,000 to ¥20,000](https://japanlivinglife.com/articles/english-speaking-therapists-japan-guide) out of pocket. The main exception is cognitive behavioral therapy for depression at designated hospitals. Check the price when you book.

**Know the two clinic names.** *Seishinka* (精神科) is psychiatry. *Shinryō naika* (心療内科) treats stress-related physical symptoms, such as poor sleep or stomach trouble, and is often where people go first. Both can prescribe medication.

**Visitors pay the full price.** National health insurance is for residents. On a tourist visa, you pay 100% at the clinic and claim it back from your travel insurance, so check your policy covers mental health before you fly. Many don't.

**Therapy is still a young profession here.** Japan's national licence for psychologists, *kōnin shinrishi* (公認心理師), only dates from 2017. Most therapists work in Japanese, so English speakers usually look for clinics set up for international patients, or for therapists who trained abroad.

## How to find an English-speaking therapist in Japan

**Start with IMHPJ.** [International Mental Health Professionals Japan](https://www.imhpj.org/clinical-associate-clinical-members/) is a professional association with a searchable member directory. You can filter it for therapists who are taking new clients, and many offer online sessions as well as appointments in person.

**TELL offers paid counseling too.** Alongside the free Lifeline, [TELL's counseling service](https://telljp.com/counseling-services/) offers sessions in English in Tokyo and Okinawa, and remotely anywhere in Japan.

**Ask your embassy.** Many embassies keep a list of English-speaking doctors and counselors near them. The [Australian embassy's list](https://japan.embassy.gov.au/tkyo/counselling_services.html) is one example that anyone can read.

**Book before you're in crisis.** Popular English-speaking therapists often have waiting lists. If you're moving to Japan for a year or more, make contact in your first month instead of waiting until things get bad.

## Keeping your therapist from home

For many visitors, the simplest choice is to keep seeing the therapist you already have, by video. A few things make that easier.

**Ask whether they can see you from abroad.** Licensing rules usually depend on where the client is, so some therapists can't keep treating you while you're in Japan. Ask before you leave instead of finding out at your first session.

**Plan around the time difference.** Japan is 13 to 17 hours ahead of the continental US, depending on the coast and the season. An evening session in New York is a morning session in Tokyo, which can work well before a day out.

**If you need someone new, read reviews first.** Choosing a therapist from a list of names is hard. If you're looking for someone in the US, Canada or India for online sessions, [Review My Therapy](https://reviewmytherapy.com/find-a-therapist) collects anonymous client reviews, so you can see how a therapist actually comes across before you book. And if your current therapist got you through a hard stretch, leaving them [an honest review](https://reviewmytherapy.com) helps the next person decide.

## Bringing your medication into Japan

Japan's medicine rules are stricter than most countries', and getting them wrong at the airport is serious. The health ministry's [import guidance](https://www.ncd.mhlw.go.jp/en/application2.html) is the place to check your own prescriptions.

**Some ADHD medication is banned outright.** Amphetamine, the active ingredient in Adderall, can't be brought into Japan at all, even with a prescription. Lisdexamfetamine (Vyvanse) needs permission in advance. Talk to your doctor about alternatives well before your trip.

**Many psychiatric medicines have quantity limits.** Common prescriptions are usually fine up to a set amount, roughly a month's supply. For more than that, the guidance says to contact the ministry at yakkan@mhlw.go.jp.

**Apply at least 14 days ahead.** Anything that needs permission, such as narcotics or stimulant raw materials, needs paperwork that includes a doctor's certificate. You also have to carry the medicine yourself, because it can't be sent on separately.

## How attitudes are changing

Mental health has long carried stigma in Japan, and many people still avoid talking about it at work. That's changing. More clinics, online counseling and employer programs exist than a decade ago, and Japan recorded [its lowest number of suicides on record in 2025](https://www.nippon.com/en/japan-data/h02690/). The same figures show suicides among school students reaching a record high, which is part of why support services keep expanding.

For a visitor, the practical takeaway is that help exists, but you may need to look for it in English, and ask for it directly.

## Small things that help on a trip

**Keep a routine.** Regular sleep and regular meals do a lot of the work, especially in the first week of jet lag. Getting outside in the morning light helps your body clock adjust.

**Eating alone is completely normal here.** Ramen counters, standing soba shops and set-meal *teishoku* restaurants are built for solo diners, so a quiet meal by yourself never feels odd. If ordering is the stressful part, our guide on [how to eat ramen like a local](/blog/how-to-eat-ramen-like-a-local) walks you through the ticket machine.

**Watch the drinking.** *Izakaya* (pubs) and all-you-can-drink deals are part of the fun, but alcohol makes jet lag, anxiety and low mood worse. Alternate with water or tea, and it's fine to order soft drinks.

**Leave room in the plan.** A schedule packed from opening to closing is tiring for anyone. Plan one slow afternoon in a park or a café every few days.

## Frequently asked questions

### Is there an English mental health helpline in Japan?

Yes. The TELL Lifeline (0800-300-8355) is free, anonymous and in English, though not open 24 hours. The Yorisoi Hotline (0120-279-338, press 2) takes calls in English and other languages from 10:00 to 22:00. In an emergency, call 119.

### Does Japanese health insurance cover therapy?

Psychiatrist visits are covered for residents with national health insurance. Counseling and talk therapy usually aren't, so expect to pay the full fee for most English-speaking therapists.

### How much does therapy cost in Japan?

Private counseling in English is commonly ¥10,000 to ¥20,000 a session, paid out of pocket. Visitors without Japanese insurance pay the full price for psychiatry too, so check what your travel insurance covers.

### Can I bring antidepressants or ADHD medication to Japan?

Many antidepressants are fine in personal amounts, but check the health ministry's guidance for your exact medicine. Adderall is banned, and some other ADHD medicines need permission before you arrive.

### Can I keep seeing my therapist from home while I'm in Japan?

Often, by video. Ask your therapist first, because licensing rules sometimes stop them from treating clients who are abroad.

